app.post(
  '/api/admin/orders/:id/delhivery',
  requireAdmin,
  async (req, res) => {
    const id = Number(req.params.id);

    if (!Number.isInteger(id) || id < 1) {
      return res.status(400).json({ error: 'Invalid order ID.' });
    }

    const token = process.env.DELHIVERY_API_TOKEN;
    const pickupLocation = process.env.DELHIVERY_PICKUP_LOCATION;

    if (!token || !pickupLocation) {
      return res.status(503).json({
        error: 'Configure DELHIVERY_API_TOKEN and DELHIVERY_PICKUP_LOCATION in Render.'
      });
    }

    try {
      const result = await pool.query(
        `SELECT o.*,
                COALESCE(
                  json_agg(
                    json_build_object(
                      'name', oi.product_name,
                      'price', oi.unit_price,
                      'quantity', oi.quantity
                    )
                  ) FILTER (WHERE oi.id IS NOT NULL),
                  '[]'::json
                ) AS items
         FROM orders o
         LEFT JOIN order_items oi ON oi.order_id = o.id
         WHERE o.id = $1
         GROUP BY o.id`,
        [id]
      );

      const order = result.rows[0];

      if (!order) {
        return res.status(404).json({ error: 'Order not found.' });
      }

      if (order.delhivery_waybill) {
        return res.status(409).json({
          error: 'This order already has a Delhivery AWB.',
          waybill: order.delhivery_waybill,
          trackingUrl: order.delhivery_tracking_url
        });
      }

      if (!order.pincode || !/^\d{6}$/.test(order.pincode)) {
        return res.status(400).json({
          error: 'A valid delivery PIN code is required.'
        });
      }

      const weightGrams = Number(req.body?.weightGrams || 500);

      if (!Number.isFinite(weightGrams) ||
          weightGrams < 1 || weightGrams > 50000) {
        return res.status(400).json({
          error: 'weightGrams must be between 1 and 50000.'
        });
      }

      // Confirm the exact payload and endpoint required by your
      // Delhivery account and API version before enabling live use.
      const payload = {
        shipments: [{
          name: order.customer_name,
          add: order.address,
          pin: order.pincode,
          phone: order.phone,
          order: String(order.id),
          payment_mode: order.payment_method === 'COD' ? 'COD' : 'Prepaid',
          cod_amount: order.payment_method === 'COD'
            ? Number(order.total)
            : 0,
          products_desc: order.items
            .map(item => `${item.name} x ${item.quantity}`)
            .join(', ')
            .slice(0, 500),
          quantity: String(
            order.items.reduce((sum, item) => sum + Number(item.quantity), 0)
          ),
          total_amount: Number(order.total),
          weight: weightGrams,
          seller_name: process.env.DELHIVERY_SELLER_NAME || 'Kapil Medical',
          seller_add: process.env.DELHIVERY_SELLER_ADDRESS || '',
          return_add: process.env.DELHIVERY_RETURN_ADDRESS || '',
          return_pin: process.env.DELHIVERY_RETURN_PIN || '',
          shipment_length: Number(req.body?.lengthCm || 15),
          shipment_width: Number(req.body?.widthCm || 10),
          shipment_height: Number(req.body?.heightCm || 8)
        }],
        pickup_location: {
          name: pickupLocation
        }
      };

      const response = await fetch(
        process.env.DELHIVERY_ORDER_URL ||
          'https://track.delhivery.com/api/cmu/create.json',
        {
          method: 'POST',
          headers: {
            'Authorization': `Token ${token}`,
            'Content-Type': 'application/json'
          },
          body: new URLSearchParams({
            format: 'json',
            data: JSON.stringify(payload)
          }),
          signal: AbortSignal.timeout(20000)
        }
      );

      const responseText = await response.text();

      let data;
      try {
        data = JSON.parse(responseText);
      } catch {
        data = { raw: responseText.slice(0, 1000) };
      }

      if (!response.ok) {
        console.error('Delhivery rejected shipment:', response.status);
        return res.status(502).json({
          error: 'Delhivery did not accept the shipment.',
          providerStatus: response.status
        });
      }

      const waybill =
        data?.packages?.[0]?.waybill ||
        data?.waybill ||
        data?.upload_wbn ||
        null;

      const providerSuccess =
        data?.success === true ||
        data?.success === 'true' ||
        Boolean(waybill);

      if (!providerSuccess) {
        console.error('Delhivery response:', JSON.stringify(data).slice(0, 1500));
        return res.status(502).json({
          error: 'Shipment creation was not confirmed by Delhivery.',
          providerResponse: data
        });
      }

      const trackingUrl = waybill
        ? `https://www.delhivery.com/track/package/${encodeURIComponent(waybill)}`
        : null;

      await pool.query(
        `UPDATE orders
         SET delhivery_waybill = $1,
             delhivery_status = $2,
             delhivery_tracking_url = $3,
             delhivery_response = $4::jsonb,
             delhivery_created_at = CURRENT_TIMESTAMP,
             status = 'Shipped'
         WHERE id = $5`,
        [
          waybill,
          'Shipment created',
          trackingUrl,
          JSON.stringify(data),
          id
        ]
      );

      res.json({
        ok: true,
        waybill,
        trackingUrl,
        message: 'Shipment creation response received.'
      });
    } catch (error) {
      console.error('Delhivery integration error:', error.message);
      res.status(502).json({
        error: 'Could not complete the shipment request. Check server logs and Delhivery status before retrying.'
      });
    }
  }
);

