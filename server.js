const razorpay =
  process.env.RAZORPAY_KEY_ID &&
  process.env.RAZORPAY_KEY_SECRET
    ? new Razorpay({
        key_id: process.env.RAZORPAY_KEY_ID,
        key_secret: process.env.RAZORPAY_KEY_SECRET
      })
    : null;

app.post('/api/payment/razorpay/order', async (req, res) => {
  if (!razorpay) {
    return res.status(503).json({
      error: 'Razorpay credentials are not configured.'
    });
  }

  try {
    const details = validateDetails(req.body);
    const calculated = await calculateItems(req.body?.items);

    const paymentOrder = await razorpay.orders.create({
      amount: Math.round(calculated.total * 100),
      currency: 'INR',
      receipt: `km-${Date.now()}`
    });

    // This endpoint only creates a Razorpay payment order.
    // Do not reduce stock or create a paid store order here.
    // Complete order creation after verified payment in the
    // payment-verification endpoint using a DB transaction.

    req.session.pendingPayment = {
      razorpayOrderId: paymentOrder.id,
      details,
      items: calculated.items,
      total: calculated.total,
      customerId: req.session?.customer?.id || null
    };

    res.json({
      ok: true,
      key: process.env.RAZORPAY_KEY_ID,
      razorpayOrder: paymentOrder
    });
  } catch (error) {
    console.error('Razorpay order error:', error.message);
    res.status(400).json({ error: error.message });
  }
});

