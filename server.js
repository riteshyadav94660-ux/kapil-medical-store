async function createOrder(details, calculated, customerId, paymentMethod) {
  return withTransaction(async client => {
    // Recheck and reserve stock inside the transaction.
    for (const item of calculated.items) {
      const updated = await client.query(
        `UPDATE products
         SET stock = stock - $1
         WHERE id = $2 AND stock >= $1
         RETURNING id`,
        [item.quantity, item.productId]
      );

      if (!updated.rows.length) {
        throw Error(`Insufficient stock for ${item.name}.`);
      }
    }

    const orderResult = await client.query(
      `INSERT INTO orders
       (customer_name, phone, address, pincode, payment_method,
        status, total, customer_id)
       VALUES($1, $2, $3, $4, $5, 'Placed', $6, $7)
       RETURNING id, total, status, created_at`,
      [
        details.customerName,
        details.phone,
        details.address,
        details.pincode,
        paymentMethod,
        calculated.total,
        customerId || null
      ]
    );

    const order = orderResult.rows[0];

    for (const item of calculated.items) {
      await client.query(
        `INSERT INTO order_items
         (order_id, product_id, product_name, unit_price, quantity)
         VALUES($1, $2, $3, $4, $5)`,
        [
          order.id,
          item.productId,
          item.name,
          item.price,
          item.quantity
        ]
      );
    }

    // Private tracking token: store only its SHA-256 hash.
    const token = crypto.randomBytes(32).toString('hex');

    await client.query(
      'UPDATE orders SET tracking_token_hash=$1 WHERE id=$2',
      [hashToken(token), order.id]
    );

    return { order, token };
  });
}

app.post('/api/orders', async (req, res) => {
  try {
    const details = validateDetails(req.body);
    const calculated = await calculateItems(req.body?.items);

    const paymentMethod = text(
      req.body?.paymentMethod || req.body?.payment_method || 'COD',
      20
    ).toUpperCase();

    if (paymentMethod !== 'COD') {
      return res.status(400).json({
        error: 'Use the Razorpay order endpoint for online payments.'
      });
    }

    const customerId = req.session?.customer?.id || null;
    const created = await createOrder(
      details,
      calculated,
      customerId,
      'COD'
    );

    const trackingUrl =
      `${req.protocol}://${req.get('host')}` +
      `/track/${created.order.id}?token=${created.token}`;

    res.status(201).json({
      ok: true,
      order: created.order,
      trackingUrl
    });
  } catch (error) {
    console.error('Order creation error:', error.message);
    res.status(400).json({ error: error.message });
  }
});

