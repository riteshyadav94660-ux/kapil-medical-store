app.post('/api/payment/razorpay/verify', async (req, res) => {
  if (!razorpay) {
    return res.status(503).json({ error: 'Razorpay is not configured.' });
  }

  const paymentId = text(req.body?.razorpay_payment_id, 150);
  const razorpayOrderId = text(req.body?.razorpay_order_id, 150);
  const signature = text(req.body?.razorpay_signature, 300);
  const pending = req.session?.pendingPayment;

  if (!pending ||
      pending.razorpayOrderId !== razorpayOrderId ||
      !paymentId || !signature) {
    return res.status(400).json({
      error: 'Payment session is missing or invalid.'
    });
  }

  const expected = crypto
    .createHmac('sha256', process.env.RAZORPAY_KEY_SECRET)
    .update(`${razorpayOrderId}|${paymentId}`)
    .digest('hex');

  const expectedBuffer = Buffer.from(expected, 'hex');
  const suppliedBuffer = Buffer.from(signature, 'hex');

  if (expectedBuffer.length !== suppliedBuffer.length ||
      !crypto.timingSafeEqual(expectedBuffer, suppliedBuffer)) {
    return res.status(400).json({
      error: 'Payment signature verification failed.'
    });
  }

  try {
    const payment = await razorpay.payments.fetch(paymentId);

    if (payment.order_id !== razorpayOrderId ||
        Number(payment.amount) !== Math.round(pending.total * 100) ||
        payment.currency !== 'INR' ||
        !['authorized', 'captured'].includes(payment.status)) {
      return res.status(400).json({
        error: 'Payment details do not match this order.'
      });
    }

    if (payment.status !== 'captured') {
      return res.status(409).json({
        error: 'Payment is authorized but not captured. Capture it before confirming the order.'
      });
    }

    const created = await withTransaction(async client => {
      const duplicate = await client.query(
        'SELECT id FROM payments WHERE razorpay_payment_id=$1',
        [paymentId]
      );

      if (duplicate.rows.length) {
        return { duplicate: true, orderId: null };
      }

      for (const item of pending.items) {
        const stock = await client.query(
          `UPDATE products SET stock=stock-$1
           WHERE id=$2 AND stock >= $1 RETURNING id`,
          [item.quantity, item.productId]
        );

        if (!stock.rows.length) {
          throw Error(`Insufficient stock for ${item.name}.`);
        }
      }

      const orderResult = await client.query(
        `INSERT INTO orders
         (customer_name, phone, address, pincode, payment_method,
          status, total, customer_id)
         VALUES($1,$2,$3,$4,'Razorpay','Confirmed',$5,$6)
         RETURNING id, total, status, created_at`,
        [
          pending.details.customerName,
          pending.details.phone,
          pending.details.address,
          pending.details.pincode,
          pending.total,
          pending.customerId
        ]
      );

      const order = orderResult.rows[0];

      for (const item of pending.items) {
        await client.query(
          `INSERT INTO order_items
           (order_id, product_id, product_name, unit_price, quantity)
           VALUES($1,$2,$3,$4,$5)`,
          [order.id, item.productId, item.name, item.price, item.quantity]
        );
      }

      await client.query(
        `INSERT INTO payments
         (razorpay_payment_id, razorpay_order_id, order_id)
         VALUES($1,$2,$3)`,
        [paymentId, razorpayOrderId, order.id]
      );

      return { duplicate: false, orderId: order.id };
    });

    delete req.session.pendingPayment;

    if (created.duplicate) {
      return res.status(409).json({
        error: 'This payment has already been processed.'
      });
    }

    res.json({ ok: true, orderId: created.orderId });
  } catch (error) {
    console.error('Razorpay verification error:', error.message);
    res.status(500).json({
      error: 'Payment was verified but order finalization needs review. Do not pay again; contact support.'
    });
  }
});

