function setCustomerSession(req, res, customer) {
  req.session.regenerate(error => {
    if (error) {
      return res.status(500).json({
        error: 'Could not create session.'
      });
    }

    req.session.customer = {
      id: customer.id,
      name: customer.name,
      phone: customer.phone
    };

    req.session.save(saveError => {
      if (saveError) {
        return res.status(500).json({
          error: 'Could not save session.'
        });
      }

      res.json({
        ok: true,
        customer: req.session.customer
      });
    });
  });
}

function validImageUrl(value) {
  if (typeof value !== 'string') return '';

  const raw = value.trim();

  try {
    const url = new URL(raw);
    if (url.protocol === 'https:') return url.href;
  } catch {}

  const match = raw.match(
    /^data:image\/(jpeg|png|webp|gif);base64,([A-Za-z0-9+/]+={0,2})$/
  );

  if (!match) return '';

  const buffer = Buffer.from(match[2], 'base64');

  return buffer.length && buffer.length <= 1024 * 1024
    ? raw
    : '';
}

async function initDb() {
  // These CREATE TABLE statements only create missing tables.
  // Existing tables may need schema-specific migrations.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS admins (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS customers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      phone TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'General',
      price NUMERIC(12,2) NOT NULL,
      stock INTEGER NOT NULL DEFAULT 0,
      prescription_required INTEGER NOT NULL DEFAULT 0,
      image_url TEXT NOT NULL DEFAULT ''
    );

    CREATE TABLE IF NOT EXISTS orders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_name TEXT NOT NULL,
      phone TEXT NOT NULL,
      address TEXT NOT NULL,
      pincode TEXT NOT NULL DEFAULT '',
      payment_method TEXT NOT NULL DEFAULT 'COD',
      status TEXT NOT NULL DEFAULT 'Placed',
      total NUMERIC(12,2) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      customer_id BIGINT REFERENCES customers(id),
      tracking_token_hash TEXT,
      stock_restored INTEGER NOT NULL DEFAULT 0
    );

    CREATE TABLE IF NOT EXISTS order_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
      product_id BIGINT,
      product_name TEXT NOT NULL,
      unit_price NUMERIC(12,2) NOT NULL,
      quantity INTEGER NOT NULL
    );

    CREATE TABLE IF NOT EXISTS payments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      razorpay_payment_id TEXT NOT NULL UNIQUE,
      razorpay_order_id TEXT NOT NULL,
      order_id BIGINT NOT NULL REFERENCES orders(id)
    );
  `);

  // Additive columns used by shipment tracking.
  await pool.query(`
    ALTER TABLE products
      ADD COLUMN IF NOT EXISTS image_url TEXT NOT NULL DEFAULT '';

    ALTER TABLE orders
      ADD COLUMN IF NOT EXISTS pincode TEXT NOT NULL DEFAULT '',
      ADD COLUMN IF NOT EXISTS tracking_token_hash TEXT,
      ADD COLUMN IF NOT EXISTS stock_restored INTEGER NOT NULL DEFAULT 0,
      ADD COLUMN IF NOT EXISTS customer_id BIGINT,
      ADD COLUMN IF NOT EXISTS delhivery_waybill TEXT,
      ADD COLUMN IF NOT EXISTS delhivery_status TEXT,
      ADD COLUMN IF NOT EXISTS delhivery_tracking_url TEXT,
      ADD COLUMN IF NOT EXISTS delhivery_response JSONB,
      ADD COLUMN IF NOT EXISTS delhivery_created_at TIMESTAMPTZ;
  `);

  // Never overwrite existing admin credentials automatically.
  const adminCount = Number(
    (await pool.query('SELECT COUNT(*) AS n FROM admins')).rows[0].n
  );

  if (!adminCount) {
    const username = text(process.env.ADMIN_USERNAME || 'admin', 100);
    const password = process.env.ADMIN_PASSWORD;

    if (!password) {
      throw new Error(
        'Set ADMIN_USERNAME and ADMIN_PASSWORD in Render before first startup.'
      );
    }

    await pool.query(
      'INSERT INTO admins(username, password_hash) VALUES($1, $2)',
      [username, await bcrypt.hash(password, 12)]
    );
  }
}

function validateProduct(body) {
  const name = text(body?.name, 150);
  const category = text(body?.category, 100) || 'General';
  const price = number(body?.price);
  const stock = number(body?.stock);
  const prescription_required = body?.prescription_required ? 1 : 0;
  const image_url = validImageUrl(body?.image_url);

  if (!name) throw Error('Product name is required.');
  if (!Number.isFinite(price) || price < 0) {
    throw Error('Enter a valid product price.');
  }
  if (!Number.isInteger(stock) || stock < 0) {
    throw Error('Enter a valid stock quantity.');
  }
  if (body?.image_url && !image_url) {
    throw Error('Invalid image URL or image is larger than 1 MB.');
  }

  return {
    name,
    category,
    price,
    stock,
    prescription_required,
    image_url
  };
}

function validateDetails(body) {
  const customerName = text(
    body?.customerName || body?.customer_name,
    100
  );
  const phone = normalizePhone(body?.phone);
  const address = text(body?.address, 500);
  const pincode = text(body?.pincode, 10);

  if (!customerName) throw Error('Customer name is required.');
  if (!/^[6-9]\d{9}$/.test(phone)) {
    throw Error('Enter a valid 10-digit mobile number.');
  }
  if (!address) throw Error('Delivery address is required.');
  if (pincode && !/^\d{6}$/.test(pincode)) {
    throw Error('Enter a valid 6-digit PIN code.');
  }

  return { customerName, phone, address, pincode };
}

async function calculateItems(items) {
  if (!Array.isArray(items) || !items.length || items.length > 50) {
    throw Error('Your cart is empty or invalid.');
  }

  const combined = new Map();

  for (const item of items) {
    const id = Number(item.productId ?? item.product_id ?? item.id);
    const quantity = Number(item.quantity);

    if (!Number.isInteger(id) || id < 1) {
      throw Error('Invalid product in cart.');
    }
    if (!Number.isInteger(quantity) || quantity < 1 || quantity > 99) {
      throw Error('Invalid product quantity.');
    }

    combined.set(id, (combined.get(id) || 0) + quantity);
  }

  const result = [];
  let total = 0;

  for (const [id, quantity] of combined) {
    const query = await pool.query(
      `SELECT id, name, category, price, stock,
              prescription_required, image_url
       FROM products WHERE id = $1`,
      [id]
    );

    const product = query.rows[0];

    if (!product) throw Error('A product in your cart no longer exists.');
    if (Number(product.stock) < quantity) {
      throw Error(`Not enough stock for ${product.name}.`);
    }
    if (product.prescription_required) {
      throw Error(
        `${product.name} requires prescription verification.`
      );
    }

    const price = Number(product.price);
    total += price * quantity;

    result.push({
      productId: product.id,
      name: product.name,
      price,
      quantity
    });
  }

  return {
    items: result,
    total: Math.round(total * 100) / 100
  };
}

async function withTransaction(callback) {
  const client = await pool.connect();

  try {
    await client.query('BEGIN');
    const result = await callback(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    try {
      await client.query('ROLLBACK');
    } catch {}
    throw error;
  } finally {
    client.release();
  }
}
